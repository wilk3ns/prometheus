// Database tooling: dbmate migrations, deterministic schema dump (db/schema.sql) and Kysely codegen.
//   node scripts/db.mjs migrate   -> dbmate up, DBOS system schema, dump db/schema.sql, regenerate Kysely types
//   node scripts/db.mjs rollback  -> dbmate rollback (one step)
//   node scripts/db.mjs reset     -> drop + up; only for databases named *_it (integration tests)
//   node scripts/db.mjs verify    -> on a scratch database: up -> dump A -> down (ALL) -> up -> dump B;
//                                    asserts A == B == committed db/schema.sql and Kysely types up to date
import { execFileSync, spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { REPO_ROOT, adminUrl, applyLocalDefaults, required } from './env.mjs';

applyLocalDefaults();

const MIGRATIONS_DIR = `${REPO_ROOT}db/migrations`;
const SCHEMA_FILE = `${REPO_ROOT}db/schema.sql`;
const TYPES_FILE = `${REPO_ROOT}packages/db/src/generated/db.ts`;
const COMPOSE_FILE = `${REPO_ROOT}deploy/compose/compose.yaml`;
const requireFromRoot = createRequire(`${REPO_ROOT}package.json`);

/** Absolute path of a package's JS bin entry, run with the current node (no shell, path-with-spaces safe). */
function binScript(pkg, name) {
  const manifestPath = requireFromRoot.resolve(`${pkg}/package.json`);
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  return join(dirname(manifestPath), manifest.bin[name]);
}

function runNodeBin(pkg, name, args, label) {
  const res = spawnSync(process.execPath, [binScript(pkg, name), ...args], { stdio: 'inherit' });
  if (res.status !== 0) throw new Error(`${label} failed (exit ${res.status})`);
}

function dbmate(database, ...args) {
  runNodeBin(
    'dbmate',
    'dbmate',
    ['--url', adminUrl(database), '--migrations-dir', MIGRATIONS_DIR, '--no-dump-schema', '--wait', ...args],
    `dbmate ${args.join(' ')} (${database})`,
  );
}

/**
 * Schema-only dump via the postgres container's own pg_dump (matches the server major version; no host
 * client required). Privileges are kept on purpose: the GRANT/REVOKE set IS the role-isolation contract.
 */
function dumpSchema(database) {
  const ddl = execFileSync(
    'docker',
    [
      'compose',
      '-f',
      COMPOSE_FILE,
      'exec',
      '-T',
      'postgres',
      'pg_dump',
      '-U',
      required('PG_ADMIN_USER'),
      '--schema-only',
      '--no-owner',
      '--restrict-key=prometheusschemadump',
      // DBOS owns and versions its own system schema (scripts/dbos-migrate.mjs); it is not a dbmate artifact.
      '--exclude-schema=dbos',
      database,
    ],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  const versions = execFileSync(
    'docker',
    [
      'compose',
      '-f',
      COMPOSE_FILE,
      'exec',
      '-T',
      'postgres',
      'psql',
      '-U',
      required('PG_ADMIN_USER'),
      '-d',
      database,
      '-At',
      '-c',
      'SELECT version FROM public.schema_migrations ORDER BY version',
    ],
    { encoding: 'utf8' },
  )
    .trim()
    .split(/\r?\n/)
    .filter(Boolean);
  const body = ddl.replace(/\r\n/g, '\n').replace(/^-- Dumped (from|by) .*\n/gm, '');
  return [
    '-- AUTO-GENERATED by `pnpm db:migrate` (scripts/db.mjs). Do not edit; diff-checked by `pnpm db:verify`.',
    '-- Cluster-wide roles (wiki_reader, wiki_writer, app_core) are created by the migration, not by this dump.',
    body.trimEnd(),
    '',
    '-- dbmate schema_migrations',
    ...versions.map((v) => `-- ${v}`),
    '',
  ].join('\n');
}

function codegen(database, outFile) {
  runNodeBin(
    'kysely-codegen',
    'kysely-codegen',
    [
      '--dialect',
      'postgres',
      '--url',
      adminUrl(database),
      '--include-pattern',
      '(wiki|econ).*',
      // `date` columns stay 'YYYY-MM-DD' strings (packages/db registers the matching pg type parser), so
      // calendar dates never pick up a local-timezone shift.
      '--date-parser',
      'string',
      '--out-file',
      outFile,
      '--log-level',
      'error',
    ],
    `kysely-codegen (${database})`,
  );
}

function psql(database, sql) {
  return execFileSync(
    'docker',
    [
      'compose',
      '-f',
      COMPOSE_FILE,
      'exec',
      '-T',
      'postgres',
      'psql',
      '-U',
      required('PG_ADMIN_USER'),
      '-d',
      database,
      '-At',
      '-v',
      'ON_ERROR_STOP=1',
      '-c',
      sql,
    ],
    { encoding: 'utf8' },
  ).trim();
}

function dbosMigrate(database) {
  const res = spawnSync(process.execPath, [`${REPO_ROOT}scripts/dbos-migrate.mjs`, database], {
    stdio: 'inherit',
  });
  if (res.status !== 0) throw new Error(`dbos migrate failed (${database})`);
}

/** Number of committed dbmate migrations (verify rolls ALL of them back, not just the latest). */
function migrationCount() {
  return readdirSync(MIGRATIONS_DIR).filter((f) => f.endsWith('.sql')).length;
}

const command = process.argv[2];
const database = required('PG_DATABASE');

if (command === 'migrate') {
  dbmate(database, 'up');
  dbosMigrate(database);
  writeFileSync(SCHEMA_FILE, dumpSchema(database));
  codegen(database, TYPES_FILE);
  console.log(`db:migrate OK -> ${database}; wrote db/schema.sql and packages/db/src/generated/db.ts`);
} else if (command === 'reset') {
  // Integration-test databases only: drop + migrate from scratch, no artifact writes.
  if (!database.endsWith('_it'))
    throw new Error(`db reset refuses to touch '${database}' (name must end in _it)`);
  dbmate(database, 'drop');
  dbmate(database, 'up');
  dbosMigrate(database);
  console.log(`db:reset OK -> ${database}`);
} else if (command === 'rollback') {
  dbmate(database, 'rollback');
  console.log(`db:rollback OK -> ${database}`);
} else if (command === 'verify') {
  const scratch = `${database}_migcheck`;
  dbmate(scratch, 'drop');
  try {
    dbmate(scratch, 'up');
    const first = dumpSchema(scratch);
    for (let i = 0; i < migrationCount(); i += 1) dbmate(scratch, 'rollback');
    const leftover = psql(
      scratch,
      "SELECT count(*) FROM pg_namespace WHERE nspname IN ('wiki','econ','matching')",
    );
    if (leftover !== '0') throw new Error('migrate:down left schema wiki/econ/matching in place');
    dbmate(scratch, 'up');
    const second = dumpSchema(scratch);
    if (first !== second) throw new Error('schema differs between first up and up-after-down');
    const committed = readFileSync(SCHEMA_FILE, 'utf8').replace(/\r\n/g, '\n');
    if (committed !== first)
      throw new Error('db/schema.sql is stale: run `pnpm db:migrate` and commit the result');
    const tmpTypes = `${REPO_ROOT}packages/db/src/generated/.verify-db.ts`;
    codegen(scratch, tmpTypes);
    const fresh = readFileSync(tmpTypes, 'utf8');
    rmSync(tmpTypes, { force: true });
    if (fresh.replace(/\r\n/g, '\n') !== readFileSync(TYPES_FILE, 'utf8').replace(/\r\n/g, '\n')) {
      throw new Error('Kysely types are stale: run `pnpm db:migrate` and commit the result');
    }
    console.log('db:verify OK -> up/down/up clean; schema.sql and Kysely types match a fresh migration');
  } finally {
    dbmate(scratch, 'drop');
  }
} else {
  console.error('usage: node scripts/db.mjs <migrate|rollback|reset|verify>');
  process.exit(2);
}
