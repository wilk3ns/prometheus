import { randomFillSync } from 'node:crypto';
import type { ClockPort } from './clock.js';

declare const uuidBrand: unique symbol;
/** RFC 9562 UUID string (lower-case, hyphenated). */
export type Uuid = string & { readonly [uuidBrand]: true };

export interface IdGen {
  next(): Uuid;
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

export function isUuid(value: string): value is Uuid {
  return UUID_RE.test(value);
}

export type RandomSource = (bytes: Uint8Array) => void;

const cryptoRandom: RandomSource = (bytes) => {
  randomFillSync(bytes);
};

/**
 * UUIDv7 generator (RFC 9562 §5.7) with a 12-bit monotonic counter in `rand_a` (§6.2 method 1):
 * IDs generated by one generator are strictly increasing even within the same millisecond.
 */
export function createUuidV7Generator(clock: ClockPort, random: RandomSource = cryptoRandom): IdGen {
  let lastMs = -1;
  let counter = 0;

  return {
    next(): Uuid {
      let ms = clock.now().getTime();
      const bytes = new Uint8Array(16);
      random(bytes);

      if (ms <= lastMs) {
        ms = lastMs;
        counter += 1;
        if (counter > 0xfff) {
          ms += 1;
          counter = (bytes[6] ?? 0) & 0x07;
        }
      } else {
        // Seed the counter low so it has headroom to increment within the millisecond.
        counter = (bytes[6] ?? 0) & 0x07;
      }
      lastMs = ms;

      const ts = BigInt(ms);
      for (let i = 0; i < 6; i += 1) {
        bytes[i] = Number((ts >> BigInt(8 * (5 - i))) & 0xffn);
      }
      bytes[6] = 0x70 | ((counter >> 8) & 0x0f);
      bytes[7] = counter & 0xff;
      bytes[8] = 0x80 | ((bytes[8] ?? 0) & 0x3f);

      const hex = Buffer.from(bytes).toString('hex');
      return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}` as Uuid;
    },
  };
}
